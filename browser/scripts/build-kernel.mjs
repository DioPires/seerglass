// Compile the exact bank-search kernel (src/exact-kernel.c) and write it into
// src/exact-kernel-wasm.ts as base64, the form the repository keeps it in (it holds no binary
// file). Needs clang with the wasm32 target and wasm-ld (LLVM's lld):
//
//   node scripts/build-kernel.mjs          write src/exact-kernel-wasm.ts
//   node scripts/build-kernel.mjs --check  exit 1 when the written module differs from a fresh build
//
// The kept module records the compiler's version line. Another version of clang may emit other
// bytes for the same source; test/exact-kernel.test.ts compares the bytes only when the
// installed clang reports the recorded version, and checks the kernel's answers in every case.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const SOURCE = join(root, "src/exact-kernel.c");
export const OUTPUT = join(root, "src/exact-kernel-wasm.ts");
export const FLAGS = ["--target=wasm32", "-O3", "-msimd128", "-ffp-contract=off", "-nostdlib", "-fno-builtin",
  "-Wl,--no-entry", "-Wl,--import-memory", "-Wl,--export=__heap_base", "-Wl,--strip-debug"];

/** The first line of `clang --version`. */
export function clangVersion() {
  return execFileSync("clang", ["--version"], { encoding: "utf8" }).split("\n")[0].trim();
}

/** The kernel's bytes, freshly compiled. */
export function compileKernel() {
  const folder = mkdtempSync(join(tmpdir(), "exact-kernel-"));
  try {
    const out = join(folder, "kernel.wasm");
    execFileSync("clang", [...FLAGS, "-o", out, SOURCE], { stdio: ["ignore", "inherit", "inherit"] });
    return readFileSync(out);
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
}

/** The text of src/exact-kernel-wasm.ts for these bytes. */
export function moduleText(bytes, version) {
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const b64 = bytes.toString("base64");
  const lines = b64.match(/.{1,100}/g).map((line) => `  "${line}"`).join(" +\n");
  return `// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/build-kernel.mjs from src/exact-kernel.c: do not edit. Rebuild with
// \`node scripts/build-kernel.mjs\` after changing the source.

/** The compiler that wrote these bytes (\`clang --version\`, first line). */
export const EXACT_KERNEL_COMPILER = ${JSON.stringify(version)};
/** The flags it was given. */
export const EXACT_KERNEL_FLAGS: readonly string[] = ${JSON.stringify(FLAGS)};
/** SHA-256 of the module's bytes. */
export const EXACT_KERNEL_SHA256 = "${sha256}";
/** The WebAssembly module, base64. */
export const EXACT_KERNEL_BASE64 =
${lines};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = moduleText(compileKernel(), clangVersion());
  if (process.argv.includes("--check")) {
    const same = readFileSync(OUTPUT, "utf8") === text;
    console.log(same ? "src/exact-kernel-wasm.ts matches a fresh build" : "src/exact-kernel-wasm.ts differs from a fresh build");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}`);
}
